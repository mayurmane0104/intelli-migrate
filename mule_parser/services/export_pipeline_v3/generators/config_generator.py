"""
ConfigGenerator - Stage 5 of the v3 export pipeline.

Emits configuration artefacts at the project root and inside ``src/config/``:

* ``.env.example``         - one entry per ConfigNeed (secrets commented out).
* ``config.yaml``          - application-wide settings consumed at runtime.
* ``src/config/settings.py`` - typed runtime accessor used by the handlers.
"""
from __future__ import annotations

import json
from typing import Any

from mule_parser.services.export_pipeline.vfs import VirtualFileSystem

from ..metadata import ConfigNeed, ConfigSource, MigrationMetadata
from ..terminology import scrub_terminology


class ConfigGenerator:
    name = "config-generator"

    def generate(self, metadata: MigrationMetadata, vfs: VirtualFileSystem, *, overwrite: bool = True) -> int:
        from .merge_generator import is_merge_owned

        files_written = 0

        vfs.write(
            ".env.example",
            scrub_terminology(_render_env_example(metadata)),
            role="config",
            generator=self.name,
            overwrite=overwrite,
        )
        vfs.write(
            "config.yaml",
            scrub_terminology(_render_config_yaml(metadata)),
            role="config",
            generator=self.name,
            overwrite=overwrite,
        )
        files_written += 2

        # MERGE owns settings.py when present — do not clobber the union.
        if not is_merge_owned("src/config/settings.py", metadata):
            vfs.write(
                "src/config/settings.py",
                scrub_terminology(_render_config_accessor(metadata)),
                role="source",
                generator=self.name,
                overwrite=overwrite,
            )
            files_written += 1
        return files_written

def _collect_all_needs(metadata: MigrationMetadata) -> list[ConfigNeed]:
    needs: dict[str, ConfigNeed] = {}
    
    def _add(n: ConfigNeed):
        if n.key not in needs:
            needs[n.key] = n
        else:
            # Merge logic: preserve secrets, combine descriptions
            ex = needs[n.key]
            ex.secret = ex.secret or n.secret
            if n.description and n.description not in (ex.description or ""):
                ex.description = f"{ex.description} | {n.description}" if ex.description else n.description
            if not ex.default and n.default:
                ex.default = n.default

    for e in metadata.config.entries:
        _add(e)
    for c in metadata.connectors:
        for n in c.config_needs:
            _add(n)
    for f in metadata.functions:
        for n in f.config_needs:
            _add(n)
    for r in metadata.infrastructure.resources:
        for n in getattr(r, "config_needs", []):
            _add(n)
    if hasattr(metadata, "agent_reasoning_trace") and metadata.agent_reasoning_trace:
        for n in getattr(metadata.agent_reasoning_trace, "config_needs", []):
            _add(n)
    if hasattr(metadata, "architecture_plan") and metadata.architecture_plan:
        for n in getattr(metadata.architecture_plan, "config_needs", []):
            _add(n)

    return sorted(needs.values(), key=lambda x: x.key)

def _render_env_example(metadata: MigrationMetadata) -> str:
    slug = metadata.project_slug
    region = metadata.infrastructure.region or "us-east-1"

    lines: list[str] = [
        f"# .env.example — {slug}",
        f"# Generated by the migration pipeline. Copy to .env and fill in real values.",
        f"# Never commit the real .env to source control.",
        f"# Secret-backed lines (credentials, passwords) are prefixed with '# ' and",
        f"# must be stored in AWS Secrets Manager — see src/adapters/secrets_adapter.py.",
        "",
    ]
    
    needs = _collect_all_needs(metadata)
    
    for need in needs:
        prefix = "# " if need.secret else ""
        if need.description:
            lines.append(f"# {need.description}")
        val = need.default or ""
        if need.key.endswith("_SECRET_ARN") and not val:
            val = f"arn:aws:secretsmanager:{region}:${{AWS_ACCOUNT_ID}}:secret:{need.key.lower()}"
        lines.append(f"{prefix}{need.key}={val}")
        lines.append("")

    return "\n".join(lines)


def _render_config_yaml(metadata: MigrationMetadata) -> str:
    needs = _collect_all_needs(metadata)
    payload: dict[str, Any] = {
        "project": {
            "name": metadata.project_name,
            "slug": metadata.project_slug,
            "runtime": metadata.runtime,
        },
        "logging": {
            "level": metadata.config.log_level,
            "format": "json",
        },
        "tracing": {
            "service_name": metadata.project_slug,
            "mode": metadata.config.application_settings.get("tracing", "active"),
        },
        "metrics": {
            "namespace": metadata.config.application_settings.get("metrics_namespace", "MigrationStudio"),
        },
        "config_needs": [
            {
                "key": e.key,
                "required": e.required,
                "secret": e.secret,
                "description": e.description,
            }
            for e in needs
        ],
    }
    return _to_yaml(payload) + "\n"


def _render_config_accessor(metadata: MigrationMetadata) -> str:
    needs = _collect_all_needs(metadata)
    fields: list[str] = []
    for entry in needs:
        if entry.secret:
            fields.append(f'    "{entry.key}",')
    secret_keys = "\n".join(fields) if fields else "    # (no secret-backed entries)"
    
    env_entries = [e for e in needs if not e.secret]
    env_lines = []
    for e in env_entries:
        default = json.dumps(e.default) if e.default is not None else '""'
        env_lines.append(f'    "{e.key}": os.environ.get("{e.key}", {default}),')
    env_block = "\n".join(env_lines) if env_lines else "    # (no env-backed entries)"

    return f'''"""Typed runtime configuration accessor."""
from __future__ import annotations

import os
from dataclasses import dataclass, field
from functools import lru_cache
from typing import Any


_SECRET_KEYS: list[str] = [
{secret_keys}
]


@dataclass(frozen=True)
class AppConfig:
    """Effective configuration after loading from environment + secrets."""

    aws_region: str = os.environ.get("AWS_REGION", "{metadata.infrastructure.region}")
    log_level: str = os.environ.get("LOG_LEVEL", "{metadata.config.log_level}")
    service_name: str = os.environ.get("POWERTOOLS_SERVICE_NAME", "{metadata.project_slug}")
    environment: dict[str, Any] = field(default_factory=lambda: {{
{env_block}
    }})


@lru_cache(maxsize=1)
def get_config() -> AppConfig:
    return AppConfig()


def required_secret_keys() -> list[str]:
    return list(_SECRET_KEYS)
'''

# ---------------------------------------------------------------------------
# Minimal YAML emitter (avoids adding PyYAML as a runtime dependency).
# ---------------------------------------------------------------------------


def _to_yaml(value: Any, indent: int = 0) -> str:
    if isinstance(value, dict):
        return _dict_to_yaml(value, indent)
    if isinstance(value, list):
        return _list_to_yaml(value, indent)
    return _scalar_to_yaml(value)


def _dict_to_yaml(value: dict[str, Any], indent: int) -> str:
    if not value:
        return "{}"
    lines: list[str] = []
    pad = " " * indent
    for key, val in value.items():
        if isinstance(val, dict):
            lines.append(f"{pad}{key}:")
            if val:
                lines.append(_dict_to_yaml(val, indent + 2))
        elif isinstance(val, list):
            lines.append(f"{pad}{key}:")
            if val:
                lines.append(_list_to_yaml(val, indent + 2))
            else:
                lines.append(f"{pad}  []")
        else:
            lines.append(f"{pad}{key}: {_scalar_to_yaml(val)}")
    return "\n".join(lines)


def _list_to_yaml(value: list[Any], indent: int) -> str:
    lines: list[str] = []
    pad = " " * indent
    for item in value:
        if isinstance(item, dict):
            entries = list(item.items())
            head_key, head_val = entries[0]
            lines.append(f"{pad}- {head_key}: {_scalar_to_yaml(head_val)}")
            for key, val in entries[1:]:
                lines.append(f"{pad}  {key}: {_scalar_to_yaml(val)}")
        else:
            lines.append(f"{pad}- {_scalar_to_yaml(item)}")
    return "\n".join(lines)


def _scalar_to_yaml(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    text = str(value)
    if text == "" or any(c in text for c in ":#\n"):
        return json.dumps(text)
    return text
