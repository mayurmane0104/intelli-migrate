STRUCTURE_REGISTRY: dict[MigrationType, OutputStructureSpec] = {
    MigrationType.BATCH_SIMPLE: BATCH_SIMPLE_STRUCTURE,
    MigrationType.BATCH_COMPLEX: BATCH_COMPLEX_STRUCTURE,
    MigrationType.API: API_STRUCTURE,
}


def get_structure(migration_type: MigrationType | str) -> OutputStructureSpec:
    """
    Lookup the canonical output structure for a migration type.

    ``BATCH_LARGE`` is recognised by the classifier but not yet generated;
    it raises ``ValueError`` so callers can route to a Fargate/Batch
    fallback explicitly rather than silently producing a Lambda layout.
    """
    if isinstance(migration_type, str):
        try:
            migration_type = MigrationType(migration_type)
        except ValueError as exc:
            raise ValueError(
                f"Unknown migration type: {migration_type!r}. "
                f"Expected one of {[m.value for m in MigrationType]}"
            ) from exc
    spec = STRUCTURE_REGISTRY.get(migration_type)
    if not spec:
        raise ValueError(f"No output structure defined for migration type: {migration_type}")
    return spec


def is_batch(migration_type: MigrationType | str | None) -> bool:
    """True iff the migration type is any flavour of batch."""
    if migration_type is None:
        return False
    if isinstance(migration_type, str):
        return migration_type.startswith("batch")
    return migration_type in (
        MigrationType.BATCH_SIMPLE,
        MigrationType.BATCH_COMPLEX,
        MigrationType.BATCH_LARGE,
    )
