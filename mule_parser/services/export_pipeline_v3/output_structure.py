"""
output_structure.py — Single source of truth for the canonical output layout.

The director defined three canonical project shapes that every generated
migration must conform to:

    BATCH_SIMPLE   — EventBridge → Lambda → S3/API/DB           (15-min limit)
    BATCH_COMPLEX  — EventBridge → Step Functions → SQS → Lambdas (3 Lambdas)
    API            — API Gateway → Lambda                       (1 Lambda)

Plus a placeholder for ``BATCH_LARGE`` (EventBridge → AWS Batch / Fargate /
Glue) which is recognised by the classifier but not generated by the v3
pipeline today.

Every generator that needs to know where to write a file MUST consult
``get_structure(metadata.migration_type)`` — paths are never hardcoded in
generators. This is the architectural contract that lets us guarantee
byte-identical layouts across migrations of the same type.

Note on directory entries ending with ``/``:
    Items in ``shared_modules`` that end with ``/`` (e.g. ``"src/app/controllers/"``)
    are *dynamically populated* — the canonical shape declares the directory but
    the file set is driven by what the analysis detected (one controller per
    detected REST endpoint, one client per detected connector, …).
"""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum


class MigrationType(str, Enum):
    BATCH_SIMPLE = "batch_simple"
    BATCH_COMPLEX = "batch_complex"
    BATCH_LARGE = "batch_large"
    API = "api"


@dataclass
class OutputStructureSpec:
    """Defines all directory paths and required files for a migration type.

    Generators consume this spec via ``get_structure(migration_type)``. They
    must never hardcode any path that appears in any of these lists.
    """
    migration_type: MigrationType
    root_dir_pattern: str          # e.g. ``"{project_name}/"``
    lambda_functions: list[str]    # canonical paths to handler files
    shared_modules: list[str]      # shared `src/` module paths
    infrastructure_mode: str       # ``"terraform"`` | ``"sam"`` | ``"cdk"``
    infrastructure_files: list[str]
    test_event_files: list[str]
    requires_step_functions: bool
    requires_sqs: bool
    extra: dict = field(default_factory=dict)


