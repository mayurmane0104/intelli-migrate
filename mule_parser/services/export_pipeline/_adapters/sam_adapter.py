"""SamAdapter - emits root template.yaml + samconfig.toml on top of the canonical layout."""
from __future__ import annotations

from mule_parser.ir.project_manifest import ProjectManifest

from ..registry import AdaptResult, GenerationContext, ValidationIssue
from ..vfs import VirtualFileSystem


class SamAdapter:
    format_id = "sam"
    display_name = "AWS SAM"

    def adapt(
        self,
        manifest: ProjectManifest,
        vfs: VirtualFileSystem,
        ctx: GenerationContext,
    ) -> AdaptResult:
        result = AdaptResult(adapter=self.format_id)

        runtime = manifest.application_profile.runtime_target or _runtime_from_ctx(ctx.target_runtime)
        handler = "app.handler"
        slug = manifest.project.slug

        if not vfs.exists("template.yaml"):
            vfs.write(
                "template.yaml",
                _sam_template(slug, runtime, handler, manifest),
                role="iac",
                generator=self.format_id,
            )
            result.files_added += 1

        if not vfs.exists("samconfig.toml"):
            vfs.write(
                "samconfig.toml",
                _sam_config(slug),
                role="config",
                generator=self.format_id,
            )
            result.files_added += 1

        return result

    def validate(
        self,
        manifest: ProjectManifest,
        vfs: VirtualFileSystem,
        ctx: GenerationContext,
    ) -> list[ValidationIssue]:
        issues: list[ValidationIssue] = []
        if not vfs.exists("template.yaml"):
            issues.append(
                ValidationIssue(
                    severity="error",
                    message="SAM export missing template.yaml",
                    source=self.format_id,
                    code="SAM001",
                    path="template.yaml",
                )
            )
        if not vfs.list_paths("application"):
            issues.append(
                ValidationIssue(
                    severity="warning",
                    message="SAM export has no application/ source - sam build will fail",
                    source=self.format_id,
                    code="SAM002",
                )
            )
        return issues


def _runtime_from_ctx(target_runtime: str) -> str:
    rt = (target_runtime or "").lower()
    if rt.startswith("node"):
        return "nodejs20.x"
    if rt.startswith("java"):
        return "java21"
    if rt.startswith("dotnet"):
        return "dotnet8"
    return "python3.12"


def _sam_template(slug: str, runtime: str, handler: str, manifest: ProjectManifest) -> str:
    has_http = any("http" in c.triggers for c in manifest.components) or manifest.application_profile.capabilities.get("has_apigw")
    api_block = (
        ""
        if not has_http
        else """
      Events:
        ApiEvent:
          Type: HttpApi
          Properties:
            Path: /{proxy+}
            Method: ANY"""
    )
    return f"""AWSTemplateFormatVersion: '2010-09-09'
Transform: AWS::Serverless-2016-10-31
Description: {slug} (generated by Migration Studio)

Globals:
  Function:
    Runtime: {runtime}
    MemorySize: 512
    Timeout: 30
    Tracing: Active

Resources:
  Function:
    Type: AWS::Serverless::Function
    Properties:
      CodeUri: application/
      Handler: {handler}
      Architectures:
        - x86_64{api_block}

Outputs:
  FunctionName:
    Value: !Ref Function
"""


def _sam_config(slug: str) -> str:
    return f"""version = 0.1
[default.deploy.parameters]
stack_name = "{slug}"
resolve_s3 = true
s3_prefix = "{slug}"
region = "us-east-1"
confirm_changeset = true
capabilities = "CAPABILITY_IAM"
"""
