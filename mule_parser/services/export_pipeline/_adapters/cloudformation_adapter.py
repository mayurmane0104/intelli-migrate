"""CloudFormationAdapter - emits root cloudformation.yaml + parameters.example.json."""
from __future__ import annotations

import json

from mule_parser.ir.project_manifest import ProjectManifest

from ..registry import AdaptResult, GenerationContext, ValidationIssue
from ..vfs import VirtualFileSystem


class CloudFormationAdapter:
    format_id = "cloudformation"
    display_name = "AWS CloudFormation"

    def adapt(
        self,
        manifest: ProjectManifest,
        vfs: VirtualFileSystem,
        ctx: GenerationContext,
    ) -> AdaptResult:
        result = AdaptResult(adapter=self.format_id)
        slug = manifest.project.slug
        runtime = manifest.application_profile.runtime_target or _runtime_from_ctx(ctx.target_runtime)
        handler = "app.handler"

        if not vfs.exists("cloudformation.yaml"):
            vfs.write(
                "cloudformation.yaml",
                _cfn_root_template(slug, runtime, handler, manifest),
                role="iac",
                generator=self.format_id,
            )
            result.files_added += 1

        if not vfs.exists("parameters.example.json"):
            vfs.write(
                "parameters.example.json",
                json.dumps(
                    [
                        {"ParameterKey": "Stage", "ParameterValue": "dev"},
                        {"ParameterKey": "ArtifactBucket", "ParameterValue": "your-deploy-bucket"},
                        {"ParameterKey": "ArtifactKey", "ParameterValue": f"{slug}.zip"},
                    ],
                    indent=2,
                ),
                role="config",
                generator=self.format_id,
            )
            result.files_added += 1

        return result

    def validate(
        self,
        manifest: ProjectManifest,
        vfs: VirtualFileSystem,
        ctx: GenerationContext,
    ) -> list[ValidationIssue]:
        issues: list[ValidationIssue] = []
        if not vfs.exists("cloudformation.yaml"):
            issues.append(
                ValidationIssue(
                    severity="error",
                    message="CloudFormation export missing cloudformation.yaml",
                    source=self.format_id,
                    code="CFN001",
                    path="cloudformation.yaml",
                )
            )
        if not vfs.list_paths("infrastructure/cloudformation"):
            issues.append(
                ValidationIssue(
                    severity="info",
                    message="No nested CloudFormation templates were generated under infrastructure/cloudformation/",
                    source=self.format_id,
                    code="CFN002",
                )
            )
        return issues


def _runtime_from_ctx(target_runtime: str) -> str:
    rt = (target_runtime or "").lower()
    if rt.startswith("node"):
        return "nodejs20.x"
    if rt.startswith("java"):
        return "java21"
    if rt.startswith("dotnet"):
        return "dotnet8"
    return "python3.12"


def _cfn_root_template(slug: str, runtime: str, handler: str, manifest: ProjectManifest) -> str:
    return f"""AWSTemplateFormatVersion: '2010-09-09'
Description: {slug} (generated by Migration Studio)

Parameters:
  Stage:
    Type: String
    Default: dev
  ArtifactBucket:
    Type: String
    Description: S3 bucket holding application code
  ArtifactKey:
    Type: String
    Default: {slug}.zip

Resources:
  FunctionRole:
    Type: AWS::IAM::Role
    Properties:
      AssumeRolePolicyDocument:
        Statement:
          - Effect: Allow
            Principal:
              Service: lambda.amazonaws.com
            Action: sts:AssumeRole
      ManagedPolicyArns:
        - arn:aws:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole

  Function:
    Type: AWS::Lambda::Function
    Properties:
      Runtime: {runtime}
      Handler: {handler}
      Role: !GetAtt FunctionRole.Arn
      Code:
        S3Bucket: !Ref ArtifactBucket
        S3Key: !Ref ArtifactKey
      MemorySize: 512
      Timeout: 30

Outputs:
  FunctionName:
    Value: !Ref Function
"""
