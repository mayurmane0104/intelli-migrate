def _slug(value: str) -> str:
    import re
    text = re.sub(r"[^a-zA-Z0-9]", "_", (value or "")).lower()
    while "__" in text:
        text = text.replace("__", "_")
    return text.strip("_")


def _class_name(value: str) -> str:
    import re
    parts = [p for p in re.split(r"[\s\-_]+", value or "Component") if p]
    return "".join(p[:1].upper() + p[1:] for p in parts)


def _service_method_for_trigger(trigger: str) -> str:
    return {
        "http":     "handle_http",
        "queue":    "handle_queue_message",
        "schedule": "handle_scheduled_run",
        "event":    "handle_event",
    }.get((trigger or "").lower(), "execute")
