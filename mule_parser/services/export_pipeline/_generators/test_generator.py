def _event_for_trigger(trigger: str, comp: Component) -> dict:
    base: dict = {"component": comp.name, "trigger": trigger}
    if trigger == "http":
        evt = _api_gw_event()
        evt["body"] = '{"component": "' + comp.name + '"}'
        return evt
    if trigger == "queue":
        evt = _sqs_event()
        evt["Records"][0]["body"] = '{"component": "' + comp.name + '"}'
        return evt
    if trigger == "event":
        evt = _eventbridge_event()
        evt["detail"] = {"component": comp.name}
        return evt
    if trigger == "schedule":
        return _scheduled_event()
    return base


