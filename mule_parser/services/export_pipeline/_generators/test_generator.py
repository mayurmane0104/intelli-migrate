"""TestGenerator - tests/unit, tests/integration, tests/events.

Generates:
  tests/
  ├── unit/
  │   └── functions/
  │       └── test_<flow>.py   per component
  ├── integration/
  │   └── test_<flow>_integration.py
  └── events/
      ├── api_gateway_event.json
      ├── sqs_event.json
      └── eventbridge_event.json  (plus per-component examples)
"""
from __future__ import annotations

import json

from mule_parser.ir.project_manifest import Component, ProjectManifest

from ..registry import GenerationContext, GenerationReport
from ..vfs import VirtualFileSystem


class TestGenerator:
    name = "tests"
    runs_after: tuple[str, ...] = ("source-code", "layers")

    def supports(self, manifest: ProjectManifest, ctx: GenerationContext) -> bool:
        return True

    def generate(
        self,
        manifest: ProjectManifest,
        vfs: VirtualFileSystem,
        ctx: GenerationContext,
    ) -> GenerationReport:
        report = GenerationReport(generator=self.name)

        components = manifest.components or []

        # ── unit tests ───────────────────────────────────────────────────────
        for comp in components:
            path = f"tests/unit/functions/test_{_slug(comp.name)}.py"
            vfs.write(path, _unit_test(comp, ctx), role="test", generator=self.name)
            report.files_written += 1

        if not components:
            vfs.write("tests/unit/functions/test_example_flow.py",
                      _placeholder_unit_test(), role="test", generator=self.name)
            report.files_written += 1

        vfs.write("tests/unit/__init__.py", "", role="test", generator=self.name)
        vfs.write("tests/unit/functions/__init__.py", "", role="test", generator=self.name)
        report.files_written += 2

        # ── integration tests ────────────────────────────────────────────────
        for comp in components:
            path = f"tests/integration/test_{_slug(comp.name)}_integration.py"
            vfs.write(path, _integration_test(comp, manifest, ctx),
                      role="test", generator=self.name)
            report.files_written += 1

        if not components:
            vfs.write("tests/integration/test_example_integration.py",
                      _placeholder_integration_test(), role="test", generator=self.name)
            report.files_written += 1

        vfs.write("tests/integration/__init__.py", "", role="test", generator=self.name)
        report.files_written += 1

        # ── event payloads ───────────────────────────────────────────────────
        # Canonical AWS event shapes
        vfs.write("tests/events/api_gateway_event.json",
                  json.dumps(_api_gw_event(), indent=2), role="test", generator=self.name)
        vfs.write("tests/events/sqs_event.json",
                  json.dumps(_sqs_event(), indent=2), role="test", generator=self.name)
        vfs.write("tests/events/eventbridge_event.json",
                  json.dumps(_eventbridge_event(), indent=2), role="test", generator=self.name)
        vfs.write("tests/events/scheduled_event.json",
                  json.dumps(_scheduled_event(), indent=2), role="test", generator=self.name)
        report.files_written += 4

        # Per-component event fixtures
        for comp in components:
            for trigger in comp.triggers or ["manual"]:
                payload = _event_for_trigger(trigger, comp)
                fname = f"tests/events/{_slug(comp.name)}_{trigger}_event.json"
                vfs.write(fname, json.dumps(payload, indent=2),
                          role="test", generator=self.name)
                report.files_written += 1

        # conftest.py
        vfs.write("tests/conftest.py", _conftest(manifest), role="test", generator=self.name)
        vfs.write("tests/__init__.py", "", role="test", generator=self.name)
        report.files_written += 2

        return report


# ---------------------------------------------------------------------------
# Unit test templates
# ---------------------------------------------------------------------------

def _unit_test(comp: Component, ctx: GenerationContext) -> str:
    slug = _slug(comp.name)
    cls_service = _class_name(comp.name) + "Service"
    methods = [_service_method_for_trigger(t) for t in (comp.triggers or ["execute"])]
    test_methods = "\n\n".join(
        f"""def test_{m}(service):
    payload = {{"test_key": "test_value"}}
    result = service.{m}(payload)
    assert isinstance(result, dict)"""
        for m in methods
    )
    return f'''"""Unit tests for {comp.name!r} component.

Generated by Migration Studio. Add assertions that reflect actual
business requirements of the {comp.name!r} flow.
"""
from __future__ import annotations

import pytest

from src.functions.{slug}.service import {cls_service}


@pytest.fixture
def service() -> {cls_service}:
    return {cls_service}()


{test_methods}


def test_handler_returns_200(lambda_event, lambda_context):
    from src.functions.{slug}.handler import lambda_handler
    result = lambda_handler(lambda_event, lambda_context)
    assert result["statusCode"] == 200
'''


def _placeholder_unit_test() -> str:
    return '''"""Placeholder unit test.

Replace with real tests once migration has run and components are generated.
"""
from __future__ import annotations


def test_placeholder():
    assert True, "Replace with a real assertion"
'''


