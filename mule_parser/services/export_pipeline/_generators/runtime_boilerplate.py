"""RuntimeBoilerplateGenerator - root pyproject.toml, requirements.txt, Makefile.

Emits the Python project chassis the user expects at the project root:

* ``pyproject.toml``   - package metadata + tool config (black, ruff, pytest)
* ``requirements.txt`` - root-level runtime dependencies (aggregated from
                         every component requirements.txt and the connector
                         catalog so a `pip install -r requirements.txt` at
                         the project root yields a working environment)
* ``requirements-dev.txt`` - dev/test dependencies (pytest, moto, ...)
* ``Makefile``         - common entrypoints (`make install`, `make test`,
                         `make package`, `make deploy`)

Runs **after** ``source-code`` so we can read every per-function
``requirements.txt`` from the VFS and roll them into the root manifest.
"""
from __future__ import annotations

from typing import Any

from mule_parser.ir.project_manifest import ProjectManifest

from ..registry import GenerationContext, GenerationReport
from ..vfs import VirtualFileSystem


class RuntimeBoilerplateGenerator:
    name = "runtime-boilerplate"
    runs_after: tuple[str, ...] = ("source-code",)

    def supports(self, manifest: ProjectManifest, ctx: GenerationContext) -> bool:
        return _is_python(ctx.target_runtime)

    def generate(
        self,
        manifest: ProjectManifest,
        vfs: VirtualFileSystem,
        ctx: GenerationContext,
    ) -> GenerationReport:
        report = GenerationReport(generator=self.name)
        slug = manifest.project.slug
        runtime = manifest.application_profile.runtime_target or "python3.12"

        deps = _aggregate_requirements(vfs, manifest)
        dev_deps = _dev_requirements()

        vfs.write(
            "pyproject.toml",
            _pyproject_toml(slug, runtime, manifest),
            role="boilerplate",
            generator=self.name,
        )
        report.files_written += 1

        vfs.write(
            "requirements.txt",
            _requirements_txt(deps),
            role="boilerplate",
            generator=self.name,
        )
        report.files_written += 1

        vfs.write(
            "requirements-dev.txt",
            _requirements_txt(dev_deps),
            role="boilerplate",
            generator=self.name,
        )
        report.files_written += 1

        vfs.write(
            "Makefile",
            _makefile(slug, runtime),
            role="boilerplate",
            generator=self.name,
        )
        report.files_written += 1

        return report


def _is_python(target_runtime: str) -> bool:
    rt = (target_runtime or "").lower()
    if not rt:
        return True
    return rt.startswith("python") or rt == ""


def _aggregate_requirements(vfs: VirtualFileSystem, manifest: ProjectManifest) -> list[str]:
    """Aggregate every per-function requirements.txt + connector deps."""
    deps: set[str] = set()

    for f in vfs.files():
        if not f.path.endswith("/requirements.txt"):
            continue
        text = f.content.decode("utf-8", errors="replace")
        for line in text.splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            deps.add(line)

    catalog: list[dict[str, Any]] = manifest.extension.get("connector_catalog") or []
    for entry in catalog:
        for d in _connector_pip_deps(str(entry.get("integration_type") or "")):
            deps.add(d)

    deps.update({"aws-lambda-powertools>=2.30", "boto3>=1.34", "pydantic>=2.0"})
    return sorted(deps)


def _connector_pip_deps(integration_type: str) -> list[str]:
    return {
        "rest":       ["httpx>=0.27"],
        "soap":       ["zeep>=4.2"],
        "graphql":    ["gql>=3.5"],
        "kafka":      ["confluent-kafka>=2.6"],
        "messaging":  ["boto3>=1.34"],
        "sftp":       ["paramiko>=3.4"],
        "ftp":        ["paramiko>=3.4"],
        "salesforce": ["simple-salesforce>=1.12"],
        "sap":        ["pyrfc>=2.7"],
        "database":   ["sqlalchemy>=2.0", "psycopg[binary]>=3.2"],
    }.get((integration_type or "").lower(), [])


def _dev_requirements() -> list[str]:
    return sorted({
        "pytest>=8.0",
        "pytest-cov>=5.0",
        "pytest-asyncio>=0.23",
        "moto>=5.0",
        "boto3-stubs[essential]>=1.34",
        "ruff>=0.5",
        "black>=24.4",
        "mypy>=1.10",
    })


def _requirements_txt(deps: list[str]) -> str:
    header = "# Generated by Migration Studio. Edit freely.\n"
    return header + "\n".join(deps) + "\n"


def _pyproject_toml(slug: str, runtime: str, manifest: ProjectManifest) -> str:
    py_min = "3.10"
    rt = (runtime or "python3.12").lower()
    if rt.startswith("python"):
        try:
            py_min = rt.replace("python", "")
        except Exception:
            py_min = "3.10"
    description = manifest.project.description or f"AWS Lambda project generated from {manifest.project.source_archetype}."
    return f"""[build-system]
requires = ["setuptools>=68", "wheel"]
build-backend = "setuptools.build_meta"

[project]
name = "{slug}"
version = "{manifest.project.version or '0.1.0'}"
description = "{description}"
requires-python = ">={py_min}"
readme = "README.md"
license = {{ text = "Proprietary" }}
authors = [{{ name = "Migration Studio" }}]
dependencies = []

[project.optional-dependencies]
dev = []

[tool.setuptools]
package-dir = {{ "" = "src" }}

[tool.setuptools.packages.find]
where = ["src"]

[tool.pytest.ini_options]
minversion = "8.0"
addopts = "-ra --strict-markers --tb=short"
testpaths = ["tests"]
pythonpath = [
  "src",
  "src/layers/common/python",
  "src/shared",
]

[tool.black]
line-length = 100
target-version = ["py310"]

[tool.ruff]
line-length = 100
target-version = "py310"

[tool.ruff.lint]
select = ["E", "F", "W", "I", "B", "UP"]
ignore = ["E501"]

[tool.mypy]
python_version = "{py_min}"
strict = false
ignore_missing_imports = true
"""


def _makefile(slug: str, runtime: str) -> str:
    return f""".PHONY: help install test lint format build package deploy clean

PROJECT := {slug}
RUNTIME := {runtime}

help:
\t@echo "Available targets:"
\t@echo "  install     Install runtime + dev deps into ./.venv"
\t@echo "  test        Run pytest with coverage"
\t@echo "  lint        Run ruff + mypy"
\t@echo "  format      Run black + ruff --fix"
\t@echo "  build       Build a deployable artefact via deployment/build.sh"
\t@echo "  package     Zip the deployable artefact via deployment/package.sh"
\t@echo "  deploy      Deploy via deployment/deploy.sh"
\t@echo "  clean       Remove build/test caches"

install:
\tpython -m venv .venv
\t. .venv/bin/activate && pip install -r requirements.txt -r requirements-dev.txt

test:
\tpytest --cov=src --cov-report=term-missing

lint:
\truff check src tests
\tmypy src

format:
\tblack src tests
\truff check --fix src tests

build:
\tbash deployment/build.sh

package:
\tbash deployment/package.sh

deploy:
\tbash deployment/deploy.sh

clean:
\trm -rf .pytest_cache .ruff_cache .mypy_cache .coverage build dist *.egg-info
\tfind . -type d -name __pycache__ -prune -exec rm -rf {{}} +
"""
