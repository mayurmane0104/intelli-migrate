"""BoilerplateGenerator - README, .gitignore, .env.example at project root."""
from __future__ import annotations

from mule_parser.ir.project_manifest import ProjectManifest

from ..registry import GenerationContext, GenerationReport
from ..vfs import VirtualFileSystem


class BoilerplateGenerator:
    name = "boilerplate"
    runs_after: tuple[str, ...] = ()

    def supports(self, manifest: ProjectManifest, ctx: GenerationContext) -> bool:
        return True

    def generate(
        self,
        manifest: ProjectManifest,
        vfs: VirtualFileSystem,
        ctx: GenerationContext,
    ) -> GenerationReport:
        slug = manifest.project.slug
        runtime = manifest.application_profile.runtime_target or "python3.12"

        vfs.write("README.md", _readme(manifest, ctx, runtime),
                  role="boilerplate", generator=self.name)
        vfs.write(".gitignore", _gitignore(),
                  role="boilerplate", generator=self.name)
        vfs.write(".env.example", _env_example(slug, manifest),
                  role="boilerplate", generator=self.name)
        vfs.write("requirements.txt", _requirements_txt(manifest),
                  role="boilerplate", generator=self.name)

        return GenerationReport(generator=self.name, files_written=4)


def _requirements_txt(manifest: ProjectManifest) -> str:
    deps: list[str] = [
        "# Top-level Lambda dependencies (also see src/layers/common/python/requirements.txt)",
        "aws-lambda-powertools>=2.30",
        "pydantic>=2.0",
        "boto3>=1.34",
        "httpx>=0.27",
    ]
    for integ in manifest.integrations:
        t = (integ.integration_type or "").lower()
        extra = {
            "soap":       "zeep>=4.2",
            "database":   "sqlalchemy>=2.0",
            "kafka":      "confluent-kafka>=2.6",
            "sftp":       "paramiko>=3.4",
            "salesforce": "simple-salesforce>=1.12",
        }.get(t)
        if extra and extra not in deps:
            deps.append(extra)
    return "\n".join(deps) + "\n"


def _readme(manifest: ProjectManifest, ctx: GenerationContext, runtime: str) -> str:
    fmt = ctx.target_format
    deploy_section = {
        "zip": "Deploy by uploading the resulting ZIP to your CI/CD pipeline.",
        "sam": "Deploy with `sam build && sam deploy --guided`.",
        "cloudformation": (
            f"Deploy with "
            f"`aws cloudformation deploy --template-file cloudformation.yaml "
            f"--stack-name {manifest.project.slug}`."
        ),
        "terraform": (
            "Deploy with "
            "`terraform -chdir=terraform init && terraform -chdir=terraform apply`."
        ),
    }.get(fmt, "Deploy using your CI/CD pipeline.")

    profile = manifest.application_profile
    languages = ", ".join(profile.languages) or "(unknown)"
    archetype = profile.archetype.value
    confidence_pct = int(round(profile.archetype_confidence * 100))
    tech = profile.technology_stack
    tech_lines: list[str] = []
    if tech.integrations:
        tech_lines.append(f"- Integrations: {', '.join(tech.integrations)}")
    if tech.databases:
        tech_lines.append(f"- Databases: {', '.join(tech.databases)}")
    if tech.messaging:
        tech_lines.append(f"- Messaging: {', '.join(tech.messaging)}")
    if tech.auth:
        tech_lines.append(f"- Auth/security: {', '.join(tech.auth)}")
    if tech.configuration_sources:
        tech_lines.append(f"- Configuration sources: {', '.join(tech.configuration_sources)}")
    if tech.observability:
        tech_lines.append(f"- Observability: {', '.join(tech.observability)}")
    tech_block = "\n".join(tech_lines) if tech_lines else "- (no specific stack detected yet)"

    risks_block = (
        "\n".join(f"- {r}" for r in profile.risks)
        if profile.risks else "- (no risks flagged by the analyzer)"
    )
    recs_block = (
        "\n".join(f"- {r}" for r in profile.recommendations)
        if profile.recommendations else "- (no recommendations at this time)"
    )

    return f"""# {manifest.project.slug}

Generated by Migration Studio.

A deployable AWS project assembled from a {manifest.project.source_archetype} source application.

## Snapshot
- Application archetype: **{archetype}** (confidence {confidence_pct}%)
- Languages: **{languages}**
- Target runtime: **{runtime}**
- Complexity score: **{profile.complexity_score:.2f}** (0 = trivial, 1 = very complex)
- Components: **{len(manifest.components)}**
- Integrations: **{len(manifest.integrations)}**
- Infrastructure resources: **{len(manifest.infrastructure)}**

## Detected technology stack
{tech_block}

## Migration risks
{risks_block}

## Recommendations
{recs_block}

## Layout
- `src/functions/` - Lambda function packages (one folder per Mule flow)
- `src/layers/common/` - Shared clients, transformers, validators, observability, security
- `src/shared/` - Constants, Pydantic schemas
- `infrastructure/` - SAM template.yaml, parameter files, IAM policies
- `tests/` - Unit, integration, and event-payload test files
- `deployment/` - build.sh, package.sh, deploy.sh scripts
- `docs/` - Architecture diagram, runbook, local-setup guide
- `mule-artifacts/` - Original Mule XML flows, DataWeave scripts, properties
- `migration-report/` - Analysis reports (review only, not primary deliverables)
- `.github/workflows/deploy.yml` - GitHub Actions CI/CD pipeline

## Deployment
{deploy_section}

## Next steps
1. Read `migration-report/migration-summary.md` end-to-end.
2. Review every file in `docs/manual-review/`.
3. Run the project-validation steps in `migration-report/export-validation.json`.
4. Customise `application/` source for any project-specific logic.
"""


def _gitignore() -> str:
    return """# Migration Studio default .gitignore
.venv/
__pycache__/
*.pyc
.env
.aws-sam/
.serverless/
node_modules/
dist/
build/
.cdk.staging/
cdk.out/
.terraform/
*.tfstate
*.tfstate.backup
.DS_Store
"""


def _env_example(slug: str, manifest: ProjectManifest) -> str:
    extra_lines: list[str] = []
    for binding in manifest.configuration:
        prefix = "# " if binding.secret else ""
        if binding.default_value is not None:
            extra_lines.append(f"{prefix}{binding.key}={binding.default_value}")
        else:
            extra_lines.append(f"{prefix}{binding.key}=")
    properties_block = "\n".join(extra_lines) if extra_lines else "# (no additional properties detected)"
    return f"""# Sample environment variables for {slug}
AWS_REGION=us-east-1
LOG_LEVEL=INFO

# Migrated property bindings:
{properties_block}
"""
