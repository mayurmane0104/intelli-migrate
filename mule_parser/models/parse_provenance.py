"""
models/parse_provenance.py  –  Provenance, confidence, and audit models.

Architectural contract
──────────────────────
All data produced by the parser system falls into exactly one of two buckets:

  EXTRACTED  –  came directly from XML.  Deterministic.  Fully reliable.
                Carries a FieldProvenance that traces it to a specific
                file / line / XPath / attribute.  Confidence = 1.0 by definition.

  INFERRED   –  generated by a rule or LLM from extracted facts.
                Must carry an InferenceRecord with method, reasoning, evidence,
                and an explicit confidence < 1.0 unless proven deterministic.

These types are intentionally simple Pydantic models so they round-trip
through JSON without losing semantics.  They are NOT subclasses of existing
domain models – they are *annotations* that wrap or accompany them.
"""

from __future__ import annotations

from enum import Enum
from typing import Any
from pydantic import BaseModel, Field


# ─── Extraction side ─────────────────────────────────────────────────────────

class FieldProvenance(BaseModel):
    """Traces a single extracted value back to its XML source."""

    file: str = ""
    """Relative path of the source file (e.g. 'src/main/mule/orders.xml')."""

    line: int | None = None
    """1-based source line of the enclosing XML element."""

    xml_path: str = ""
    """Stable XPath expression identifying the element
    (e.g. '/mule/flow[@name="getOrders"]/http:listener')."""

    attribute: str = ""
    """Attribute name that held the value, or '' for text content."""

    raw_value: str = ""
    """Exact string as it appeared in the XML before any normalisation."""

    extraction_method: str = "lxml_attrib"
    """How the value was obtained: lxml_attrib | lxml_text | regex | xpath."""


# ─── Inference side ──────────────────────────────────────────────────────────

class InferenceMethod(str, Enum):
    DETERMINISTIC = "deterministic"   # pure rule, always same output for same input
    RULE_BASED    = "rule_based"      # heuristic / pattern matching
    LLM           = "llm"             # LLM completion
    FALLBACK      = "fallback"        # default / unknown


class InferenceRecord(BaseModel):
    """Documents a single inferred field value."""

    method: InferenceMethod = InferenceMethod.RULE_BASED
    confidence: float = Field(ge=0.0, le=1.0, default=0.5)
    reasoning: str = ""
    """Human-readable explanation of why this value was chosen."""

    evidence: list[str] = Field(default_factory=list)
    """Specific observations from the extracted data that support the inference
    (e.g. 'step http:listener found at line 12')."""

    alternatives_considered: list[str] = Field(default_factory=list)
    """Other values that were evaluated but rejected."""

    fallback_used: bool = False
    """True if the primary inference strategy failed and a default was used."""


# ─── Validation firewall types ────────────────────────────────────────────────

class ViolationSeverity(str, Enum):
    ERROR   = "error"    # definite contradiction between extracted and inferred
    WARNING = "warning"  # possible inconsistency, needs human review
    INFO    = "info"     # informational only


class ValidationViolation(BaseModel):
    """A single contradiction between extracted fact and inferred value."""

    field_path: str = ""
    """Dotted path to the field (e.g. 'semantic_flows[0].trigger_type')."""

    extracted_value: str = ""
    """Value from deterministic XML extraction."""

    inferred_value: str = ""
    """Value produced by the inference layer."""

    severity: ViolationSeverity = ViolationSeverity.WARNING

    message: str = ""
    """Human-readable description of the contradiction."""

    remediation: str = ""
    """Suggested fix or action."""


class ValidationReport(BaseModel):
    """Aggregated firewall report for one parse run."""

    passed: bool = True
    total_checks: int = 0
    violations: list[ValidationViolation] = Field(default_factory=list)
    error_count: int = 0
    warning_count: int = 0

    def add(self, v: ValidationViolation) -> None:
        self.violations.append(v)
        if v.severity == ViolationSeverity.ERROR:
            self.error_count += 1
            self.passed = False
        elif v.severity == ViolationSeverity.WARNING:
            self.warning_count += 1
        self.total_checks += 1


# ─── Audit trail ─────────────────────────────────────────────────────────────

class AuditEntryKind(str, Enum):
    EXTRACTION = "extraction"
    INFERENCE  = "inference"
    VALIDATION = "validation"
    ERROR      = "error"


class AuditEntry(BaseModel):
    """One step in the processing audit trail, ordered by timestamp."""

    kind: AuditEntryKind
    phase: str = ""
    """Pipeline phase label (e.g. 'semantic_analyzer', 'validation_firewall')."""

    flow_name: str = ""
    field: str = ""
    value: Any = None
    provenance: FieldProvenance | None = None
    inference: InferenceRecord | None = None
    message: str = ""


# ─── Tagged value wrapper ────────────────────────────────────────────────────
# Lightweight envelope used when a function wants to return a value AND its
# metadata in one object without altering the downstream field type.

class ExtractedValue(BaseModel):
    """A value that came directly from XML."""
    value: Any = None
    provenance: FieldProvenance


class InferredValue(BaseModel):
    """A value produced by rules or LLM."""
    value: Any = None
    inference: InferenceRecord